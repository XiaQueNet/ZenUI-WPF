namespace ZenUI.Wpf.Controls
{
    /// <summary>
    /// 指定 <see cref="ZenRadioGroup"/> 选项的显示模式。
    /// </summary>
    public enum RadioGroupDisplayMode
    {
        /// <summary>
        /// 使用传统单选按钮呈现选项。
        /// </summary>
        Radio,

        /// <summary>
        /// 使用相互独立的按钮呈现选项。
        /// </summary>
        Button,

        /// <summary>
        /// 使用相连的分段控件呈现选项。
        /// </summary>
        Segmented
    }
}
